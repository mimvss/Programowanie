###
# A program to print numerical representations of characters.
#
a= "a"
b= "b"
z= "z"
A= "A"
B= "B"
Z= "Z"
o= "1"
p= "="
r= "+"
s= "€"

print(f'a {ord(a)} ')
print(f'b {ord(b)} ')
print(f'z {ord(z)} ')
print(f'A {ord(A)} ')
print(f'B {ord(B)} ')
print(f'Z {ord(Z)} ')
print(f'o {ord(o)} ')
print(f'p {ord(p)} ')
print(f'r {ord(r)} ')
print(f's {ord(s)} ')